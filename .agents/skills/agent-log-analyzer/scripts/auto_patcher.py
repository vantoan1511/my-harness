#!/usr/bin/env python3
import os
import json

class AutoPatcher:
    """Translates telemetry anomalies into actionable rule patches and guardrail proposals."""

    def __init__(self, workspace_root=None):
        self.workspace_root = workspace_root or os.getcwd()

    def generate_proposals(self, anomaly_report):
        proposals = []

        # 1. Duplicate tool call pattern
        duplicates = anomaly_report.get("duplicate_tool_calls", [])
        if duplicates:
            tools_affected = list(set(d["tool_name"] for d in duplicates))
            proposals.append({
                "title": f"Guardrail: Intercept Duplicate Tool Calls ({', '.join(tools_affected)})",
                "target_type": "rule",
                "recommended_file": os.path.join(self.workspace_root, ".agents", "rules", "anti_duplicate_calls.md"),
                "content": self._generate_anti_duplicate_rule(duplicates),
                "reasoning": f"Detected {len(duplicates)} repeated identical tool executions causing token waste and latency."
            })

        # 2. Consecutive error loop / Thrashing pattern
        max_consecutive_errors = anomaly_report.get("max_consecutive_errors", 0)
        if max_consecutive_errors >= 3:
            proposals.append({
                "title": f"Circuit Breaker: Stop Consecutive Failures (Max {max_consecutive_errors})",
                "target_type": "rule",
                "recommended_file": os.path.join(self.workspace_root, ".agents", "rules", "circuit_breaker.md"),
                "content": self._generate_circuit_breaker_rule(max_consecutive_errors),
                "reasoning": f"Detected {max_consecutive_errors} consecutive failures without intermediate hypothesis verification."
            })

        return proposals

    def _generate_anti_duplicate_rule(self, duplicates):
        sample_tools = ", ".join(f"`{d['tool_name']}`" for d in duplicates)
        return f"""# Idempotency & Anti-Duplicate Tool Execution Guardrail

## Problem
Telemetry indicates recurring duplicate calls to {sample_tools} with identical arguments in a single task.

## Enforced Invariant
1. Before invoking a tool (especially read or query tools), verify if the result is already present in your active context or recent tool history.
2. If the identical query/command was already executed and the environment has not been modified, REUSE the existing result.
3. Never call the same retrieval command twice consecutively without an intervening state modification.
"""

    def _generate_circuit_breaker_rule(self, error_count):
        return f"""# Fast-Fail Circuit Breaker & Hypothesis Gate

## Problem
Harness detected {error_count} consecutive command/test failures without state progression.

## Enforced Invariant
1. If a command, script, or unit test fails 2 times consecutively:
   - STOP executing commands immediately.
   - Formulate a clear hypothesis explaining the failure root cause.
   - If the environment or parameters are uncertain, ask the user or inspect logs rather than guessing in a loop.
2. Never repeat the same failed command without altering the code or parameters.
"""

    def write_proposals_to_file(self, proposals, output_path):
        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write("# Autonomous Harness Learning Proposals\n\n")
            f.write("> Automatically generated by `AutoPatcher` from recent session anomalies.\n\n")
            for idx, prop in enumerate(proposals, 1):
                f.write(f"## {idx}. {prop['title']}\n\n")
                f.write(f"- **Target File:** `{prop['recommended_file']}`\n")
                f.write(f"- **Reasoning:** {prop['reasoning']}\n\n")
                f.write("```markdown\n")
                f.write(prop['content'])
                f.write("\n```\n\n---\n\n")
